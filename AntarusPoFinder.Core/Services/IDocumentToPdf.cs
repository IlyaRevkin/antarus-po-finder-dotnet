namespace AntarusPoFinder.Core.Services;

/// <summary>Превращение документа Word в PDF. Интерфейсом — потому что сам конвертер живёт в
/// приложении (он поднимает COM-объект Word или процесс LibreOffice, см.
/// <c>AntarusPoFinder.App/Services/DocxToPdfConverter.cs</c>), а нужен он в ядре, на пути выкладки на
/// хостинг. Ядро на приложение ссылаться не может и не должно: в тестах сюда подставляется заглушка,
/// а на машине без Word и LibreOffice не подставляется вовсе (null) — и выкладка честно скажет, что
/// docx выложить не смогла, вместо того чтобы положить на хостинг файл, который с телефона не
/// открывается.</summary>
public interface IDocumentToPdf
{
    /// <summary>Есть ли на этой машине чем конвертировать. Отдельно от <see cref="Convert"/>, чтобы
    /// интерфейс мог заранее сказать «PDF собрать нечем», не пытаясь.</summary>
    bool IsSupported { get; }

    /// <summary>Путь к собранному PDF или null, если не получилось (нет конвертера, документ битый,
    /// папка недоступна для записи). Долгая операция с внешним процессом — звать из фонового
    /// потока.</summary>
    string? Convert(string documentPath, string outputPdfPath);
}
