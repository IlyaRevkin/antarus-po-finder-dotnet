using System;

namespace AntarusPoFinder.Core.Services;

/// <summary>КОМУ ОБЩИЙ КОНФИГ ЕЩЁ ДОВЕРЯЕТ.
///
/// Разбор и сравнение версий в одном месте, потому что сравнивать их «на глаз» строкой — это
/// классика: «1.75.9» строкой меньше «1.9.0», и машина с новой версией оказалась бы отрезанной.
///
/// <b>Зачем вообще.</b> Почти каждая живучая беда этого года приходила от машины со старой версией:
/// удалённый подтип воскресал, прошивки висели в модерации вечно, снятый тег возвращался. Чинилось
/// это в новой версии, а разъезжалось со старой — и так по кругу, пока обе в обмене.
///
/// <b>Чего это НЕ делает.</b> Заставить обновиться нельзя: программа прошлого года не содержит ни
/// этой проверки, ни окна с просьбой, и научить её задним числом нечем. Поэтому правило работает
/// с двух сторон — новые версии не применяют правки отставших, а список подключений (см.
/// Database.SyncParticipants) называет их поимённо, чтобы было кого пнуть.</summary>
public static class VersionGate
{
    /// <summary>Разбирает «1.75.9» / «2.0.2.1» / «v1.75.9». Пусто и мусор — null, и это означает
    /// «не знаем», а не «ноль»: снимок со старой версии программы поля версии не содержит вовсе,
    /// и считать такую машину нулевой значило бы отрезать всех разом при первом же включении
    /// правила.</summary>
    public static Version? Parse(string? raw)
    {
        var text = raw?.Trim().TrimStart('v', 'V');
        if (string.IsNullOrEmpty(text)) return null;
        return Version.TryParse(text, out var version) ? version : null;
    }

    /// <summary>Достаточно ли свежа версия <paramref name="actual"/> при минимуме
    /// <paramref name="minimum"/>.
    ///
    /// Неизвестный минимум — доверяем всем (правило просто не включено). Неизвестная версия при
    /// заданном минимуме — НЕ доверяем: это снимок, собранный программой, которая о подписи ещё не
    /// знает, то есть ровно та старая версия, ради которой правило и заводили.</summary>
    public static bool IsTrusted(string? actual, string? minimum)
    {
        var floor = Parse(minimum);
        if (floor is null) return true;
        var version = Parse(actual);
        return version is not null && version >= floor;
    }

    /// <summary>Человеческое объяснение отказа — то, что увидит человек в окне и в списке
    /// подключений. Без него «заблокировано» выглядит как поломка программы.</summary>
    public static string Explain(string? actual, string? minimum)
    {
        var shown = string.IsNullOrWhiteSpace(actual) ? "неизвестна" : actual;
        return $"Версия {shown}; обмен требует не ниже {minimum}.";
    }
}
