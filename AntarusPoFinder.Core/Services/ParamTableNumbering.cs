using AntarusPoFinder.Core.Data;
using AntarusPoFinder.Core.Domain;

namespace AntarusPoFinder.Core.Services;

/// <summary>Каким номером ревизия называется ЧЕЛОВЕКУ.
///
/// <b>Задача.</b> Хранимый номер (ParamTableRevision.Number) присваивает заведшая машина: «следующий
/// свободный у меня». Между машинами он не уникален и уникальным быть не может — две машины, не
/// видевшие правок друг друга, обе назовут свою новую ревизию третьей, а обмен конфигом сведёт их в
/// один документ. Получаются две «третьих» в одном списке, и это не косметика: список ревизий
/// читают глазами как историю, а история с двумя третьими не история.
///
/// <b>Решение.</b> Номер — это ЯРЛЫК для человека, а не опознавалка. Опознавалка у ревизии одна и
/// уже есть — sync_id, на нём держится и обмен, и сведение. Поэтому хранимый номер остаётся как был
/// (он записан в чужих Summary и назван вслух до обмена), а показывается место ревизии в истории
/// документа: строки раскладываются по времени заведения и нумеруются подряд. Тогда «две третьих»
/// превращаются в честную последовательность, ОДИНАКОВУЮ у всех, у кого один и тот же набор ревизий.
///
/// <b>Что этим куплено и что отдано.</b> Куплено — одинаковый счёт у всех и отсутствие дублей.
/// Отдано — постоянство ярлыка во времени: ревизия, бывшая пятой, после приёма чужих правок,
/// сделанных РАНЬШЕ неё, станет шестой. Обмен это честно и показывает («заведена как 5» в списке).
/// Обратный размен — вечные дубли номеров, а два разных документа под одним именем хуже, чем один
/// документ, у которого номер однажды сдвинулся: дубль не лечится ничем и ничего о себе не говорит.
///
/// ⚠️ <b>Считаем ВМЕСТЕ СО СНЯТЫМИ ревизиями.</b> Тумбстоун ездит в общем конфиге, то есть виден
/// всем; выкинь его из счёта — и номера уцелевших поехали бы у того, до кого снятие ещё не доехало.
/// В списке снятая не показывается, поэтому в номерах остаётся дырка — и это правильно: дырка
/// говорит «здесь была редакция, её сняли», а сдвиг номеров не говорит ничего.
///
/// ⚠️ Сходимость, а не мгновенное совпадение. Пока чужая ревизия не приехала, счёт у машин разный —
/// но ровно в том же случае, в котором прежний способ давал ПОСТОЯННЫЙ дубль. Здесь расхождение
/// заканчивается вместе с синхронизацией.</summary>
public static class ParamTableNumbering
{
    /// <summary>Проставить номера показа. На вход — ВСЕ ревизии документа, включая снятые; порядок
    /// входного списка значения не имеет. Возвращается тот же список.
    ///
    /// Порядок счёта: время заведения, потом sync_id. Второй ключ не для красоты — created_at
    /// хранится с точностью до секунды, и две ревизии в одну секунду (импорт, быстрая правка)
    /// разложились бы на разных машинах по-разному; sync_id одинаков везде, и порядок с ним тоже.</summary>
    public static IReadOnlyList<ParamTableRevision> Apply(IEnumerable<ParamTableRevision>? revisions)
    {
        var all = (revisions ?? Enumerable.Empty<ParamTableRevision>()).ToList();
        var number = 1;
        foreach (var revision in all.OrderBy(r => r.CreatedAt, StringComparer.Ordinal)
                                    .ThenBy(r => r.SyncId, StringComparer.Ordinal)
                                    .ThenBy(r => r.Number)
                                    .ThenBy(r => r.Id ?? 0))
            revision.DisplayNumber = number++;
        return all;
    }

    /// <summary>Живые ревизии документа с проставленными номерами показа, САМАЯ СВЕЖАЯ ПЕРВОЙ —
    /// ровно в том порядке, в каком их показывает список слева.
    ///
    /// Порядок здесь по номеру показа, а не по хранимому: они могут разойтись, а список,
    /// отсортированный по одному числу и подписанный другим, выглядел бы сломанным.</summary>
    public static List<ParamTableRevision> LiveRevisions(Database db, int tableId)
    {
        var all = Apply(db.AllParamTableRevisionsIncludingDeleted(tableId));
        return all.Where(r => r.DeletedAt.Length == 0)
            .OrderByDescending(r => r.DisplayNumber)
            .ToList();
    }

    /// <summary>Как назвать ревизию в тексте. Пока хранимый и показываемый номера совпадают —
    /// просто «3». Разошлись — «5 (заведена как 3)»: под старым номером она уже названа в чужих
    /// Summary и в разговоре, и оборвать эту ниточку молча нельзя.</summary>
    public static string Label(ParamTableRevision? revision)
    {
        if (revision is null) return "";
        var shown = revision.DisplayNumber > 0 ? revision.DisplayNumber : revision.Number;
        return shown == revision.Number || revision.Number <= 0
            ? shown.ToString()
            : $"{shown} (заведена как {revision.Number})";
    }
}
