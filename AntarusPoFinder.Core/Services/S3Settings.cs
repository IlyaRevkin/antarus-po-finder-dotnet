using System;
using System.Linq;

namespace AntarusPoFinder.Core.Services;

/// <summary>Реквизиты хранилища на хостинге — куда Finder кладёт копию инструкции, чтобы ссылка под
/// QR-кодом на наклейке открывалась с телефона откуда угодно, а не только из офисной сети (решение
/// Ивана Герасимова от 05.08.2026: «размещаться будет на хостинге, а не на внутреннем ресурсе»).
///
/// Разделение полей не случайное и повторяет то, как выданы реквизиты:
///   • <see cref="Endpoint"/>/<see cref="Bucket"/>/<see cref="Region"/>/<see cref="Prefix"/> — КУДА
///     класть. Одинаковы для всего предприятия, поэтому синхронизируются между машинами;
///   • <see cref="AccessKey"/>/<see cref="SecretKey"/> — ЧЕМ подписывать. Задаются администратором
///     один раз и синхронизируются на все машины, которым положено выкладывать (см.
///     ConfigSyncService.SkipSettingsKeys — ключей там больше нет): иначе выложить инструкцию мог бы
///     только тот, кто вписал ключ у себя. Secret при этом и в БД, и в общем конфиге лежит
///     ЗАШИФРОВАННЫМ (см. ConfigService.S3SecretKey), Access Key ID — не секрет и едет строкой;
///   • <see cref="WebUrl"/> — под каким адресом файл потом виден снаружи. Это ОТДЕЛЬНЫЙ адрес
///     (fs.elitacompany.ru), а не адрес хранилища: класть и читать — разные точки входа, и путать
///     их нельзя, иначе в QR уйдёт ссылка, которую сможет открыть только владелец ключей.
///
/// Ключей на 05.08.2026 ещё нет — Иван обещал прислать файл secrets позже. Поэтому всё устроено
/// так, чтобы незаполненные ключи были ШТАТНЫМ состоянием: <see cref="CanPublish"/> false,
/// выкладка молча не делается, всё остальное работает ровно как раньше. Когда ключи придут,
/// присланный файл достаточно перетащить в Настройки → Сетевые диски (разбор — см.
/// <see cref="S3SecretsFile"/>); переустановка и правка кода не потребуются.</summary>
public sealed record S3Settings(
    string Endpoint,
    string Bucket,
    string Region,
    string Prefix,
    string AccessKey,
    string SecretKey,
    string WebUrl,
    bool Enabled)
{
    /// <summary>Справочник «имя папки → как оно называется в адресе». Кириллицы в ключах бакета и в
    /// ссылке под QR быть не должно (см. <see cref="TranslitMap"/>), а раскладка бакета повторяет
    /// раскладку целиком русского диска — значит перевод нужен ровно здесь, в одном месте, откуда его
    /// одинаково берут и выкладка, и построитель ссылки.</summary>
    public TranslitMap Translit { get; init; } = TranslitMap.Empty;

    /// <summary>Предельный размер файла, уходящего на хостинг. По умолчанию 20 МБ — столько просил
    /// владелец. Ограничение именно на ХОСТИНГ, а не на загрузку в программу вообще: на диск
    /// сколь угодно большой проект ПЛК класть можно и нужно, а вот тянуть его по ссылке с телефона в
    /// цеху — нет.</summary>
    public long MaxFileBytes { get; init; } = DefaultMaxFileBytes;

    /// <summary>Что делать с файлом сверх предела: true — не выкладывать вовсе, false — выложить, но
    /// сказать об этом. Переключателем, а не константой, по прямой просьбе: бывает документ, который
    /// «большой, но нужен», и упереться в жёсткий запрет в такой момент хуже, чем получить
    /// предупреждение.</summary>
    public bool HardSizeLimit { get; init; } = true;

    public const long DefaultMaxFileBytes = 20L * 1024 * 1024;

    /// <summary>Адрес хранилища задан настолько, что запрос вообще есть куда отправить.</summary>
    public bool HasAddress =>
        !string.IsNullOrWhiteSpace(Endpoint) && !string.IsNullOrWhiteSpace(Bucket);

    /// <summary>Ключи выданы. Отделено от <see cref="HasAddress"/> намеренно: до присылки secrets
    /// адрес уже известен и заполнен по умолчанию, а ключей нет — и интерфейс должен показывать
    /// именно это («осталось вписать ключи»), а не «ничего не настроено».</summary>
    public bool HasCredentials =>
        !string.IsNullOrWhiteSpace(AccessKey) && !string.IsNullOrWhiteSpace(SecretKey);

    /// <summary>Можно ли прямо сейчас выкладывать файлы. Выключатель отдельно от ключей, чтобы
    /// выкладку можно было приостановить, не стирая реквизиты.</summary>
    public bool CanPublish => Enabled && HasAddress && HasCredentials;

    /// <summary>Печать записи БЕЗ секретного ключа. Запись C# по умолчанию печатает все свои
    /// свойства, а <see cref="SecretKey"/> здесь лежит уже расшифрованным (см. ConfigService.S3()) —
    /// то есть одного случайного «{settings}» в тексте предупреждения, в журнале страницы
    /// «Хранилище» или в тикете хватило бы, чтобы ключ на запись во весь бакет предприятия лёг
    /// открытым текстом туда, где его прочитает кто угодно. Дешевле закрыть здесь, чем потом следить
    /// за каждым местом, где запись могла попасть в строку. «Задан/не задан» при этом видно — без
    /// этого запись стала бы бесполезна для разбора «почему не выкладывается».</summary>
    public override string ToString() =>
        $"S3Settings {{ Endpoint = {Endpoint}, Bucket = {Bucket}, Region = {Region}, Prefix = {Prefix}, " +
        $"AccessKey = {AccessKey}, SecretKey = {(string.IsNullOrEmpty(SecretKey) ? "<не задан>" : "<скрыт>")}, " +
        $"WebUrl = {WebUrl}, Enabled = {Enabled} }}";

    /// <summary>Ключ объекта в бакете для пути файла относительно корня диска прошивок. Раскладка в
    /// бакете ПОВТОРЯЕТ раскладку на диске уровень в уровень: ничего не «маппится» таблицей путей, а
    /// значит переименование подтипа или контроллера на диске автоматически действует и на хостинге.
    /// Именно поэтому ссылка под QR («веб-адрес + путь относительно корня», см. LabelLinkBuilder) и
    /// указывает ровно на тот файл, который сюда положили.
    ///
    /// Меняется по дороге только НАПИСАНИЕ каждого имени: диск у нас весь русский, а в адресе
    /// кириллицы быть не должно, поэтому каждый сегмент проходит через <see cref="Translit"/>.
    /// Структура при этом не трогается — сколько уровней было, столько и осталось.</summary>
    public string KeyFor(string relativePath)
    {
        var normalized = Translit.Path(relativePath);
        // Префикс чистится теми же правилами, что и остальные куски ключа (см. TranslitMap.SafeSegment):
        // он приходит из настройки s3_prefix, которая синхронизируется между машинами, и «..» в нём
        // увело бы запись за пределы отведённой предприятию части общего бакета ровно так же, как в
        // любом другом сегменте.
        var prefix = string.Join("/", (Prefix ?? "").Replace('\\', '/')
            .Split('/', StringSplitOptions.RemoveEmptyEntries)
            .Select(TranslitMap.SafeSegment)
            .Where(s => s.Length > 0));
        return prefix.Length > 0 ? prefix + "/" + normalized : normalized;
    }
}
