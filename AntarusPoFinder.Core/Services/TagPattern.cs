using System;

namespace AntarusPoFinder.Core.Services;

/// <summary>Тег-шаблон: звёздочка внутри тега — подстановка «здесь стоит любая последовательность
/// символов».
///
/// Зачем. Одна и та же прошивка подходит десятку шкафов, названия которых отличаются одним куском —
/// как правило амперажом: «…АМПЕРУС ПЖ-ПП-2-(9-14А)-АВР-FD-Ст», «…-(20-25А)-…» и так далее.
/// Проставлять десяток почти одинаковых тегов вручную — работа впустую, поэтому тег пишется один раз
/// с подстановкой: «Шкаф управления пожарными насосами АМПЕРУС ПЖ-ПП-2-(*-*А)-АВР-FD-Ст».
///
/// Что именно подставляет звёздочка. ЛЮБЫЕ символы, любое количество (в том числе ноль): и цифры, и
/// буквы, и пробелы, и знаки. Ограничивать её одними цифрами нельзя — в названиях шкафов варьируется
/// не только ампераж («…-FD-…» / «…-VD-…»), а помнить, где какая звёздочка «цифровая», человеку
/// незачем: у подстановки должно быть ровно одно правило, которое можно объяснить одной строкой
/// подсказки в редакторе тегов.
///
/// В обе стороны. Сравнение симметрично (<see cref="MatchesEither"/>): звёздочка может стоять и в
/// теге (наладчик ввёл конкретное название шкафа — нашлась прошивка с шаблонным тегом), и в самом
/// запросе (программист ищет по шаблону — находятся прошивки с конкретными названиями).
///
/// ТОЛЬКО ЦЕЛИКОМ. Шаблон сверяется с запросом целиком, а не «встречается внутри». Иначе тег,
/// начинающийся со звёздочки, совпадал бы с чем угодно: «*А» — это «что угодно, затем А», и любой
/// огрызок запроса формально является началом какого-нибудь такого названия. Частичный ввод при этом
/// ничего не теряет — обычный поиск по словам (Database.SearchByKeywords) и так находит прошивку по
/// буквальным кускам тега, звёздочка лишь добавляет точное попадание «весь запрос = этот тег».
///
/// Без регулярных выражений намеренно: тег — пользовательский текст, любые скобки/точки/плюсы в
/// названии шкафа пришлось бы экранировать, а построенный на лету Regex ещё и стоил бы дороже, чем
/// этот проход двумя указателями. Здесь нет ни компиляции, ни кэша — вызов дешёвый и без состояния.</summary>
public static class TagPattern
{
    /// <summary>Символ подстановки. Обычная звёздочка: её набирают одним нажатием и в живых названиях
    /// шкафов она не встречается, поэтому старые теги новый смысл не приобретают.</summary>
    public const char Wildcard = '*';

    /// <summary>Есть ли в строке подстановка вообще. Вызывается перед каждым сравнением как быстрый
    /// отсев: тегов без звёздочки — подавляющее большинство, и для них поиск обязан работать ровно
    /// так же и ровно так же быстро, как до появления шаблонов.</summary>
    public static bool HasWildcard(string? s) => !string.IsNullOrEmpty(s) && s.IndexOf(Wildcard) >= 0;

    /// <summary>Совпадает ли <paramref name="text"/> с шаблоном <paramref name="pattern"/> ЦЕЛИКОМ,
    /// без учёта регистра. Строка без звёздочек сравнивается как обычное равенство.</summary>
    public static bool Matches(string? pattern, string? text) => Glob(pattern ?? "", text ?? "");

    /// <summary>Сравнение «в обе стороны»: шаблоном считается та сторона, в которой есть звёздочка.
    /// Если звёздочки есть у обеих — пробуем оба направления (тег-шаблон против запроса-шаблона:
    /// осмысленного правила «кто из них главнее» нет, поэтому достаточно любого совпадения).
    /// Если звёздочек нет вовсе — false: обычным равенством строк занимается вызывающий, эта функция
    /// отвечает только за подстановку и не должна дублировать его сравнение.</summary>
    public static bool MatchesEither(string? a, string? b)
    {
        var hasA = HasWildcard(a);
        var hasB = HasWildcard(b);
        if (!hasA && !hasB) return false;
        if (hasA && Glob(a!, b ?? "")) return true;
        return hasB && Glob(b!, a ?? "");
    }

    /// <summary>Классический проход двумя указателями с одной точкой возврата на последнюю звёздочку:
    /// линейный в типичном случае и без рекурсии/аллокаций. starP/starT — позиция последней звёздочки
    /// и сколько текста она уже «съела»: не подошло дальше — возвращаемся и отдаём звёздочке ещё один
    /// символ. Подряд идущие звёздочки схлопываются сами собой (вторая просто переустанавливает точку
    /// возврата на ту же позицию текста).</summary>
    private static bool Glob(string pattern, string text)
    {
        int p = 0, t = 0, starP = -1, starT = 0;
        while (t < text.Length)
        {
            if (p < pattern.Length && pattern[p] == Wildcard)
            {
                starP = p++;
                starT = t;
            }
            else if (p < pattern.Length && SameChar(pattern[p], text[t]))
            {
                p++;
                t++;
            }
            else if (starP >= 0)
            {
                // Откат: звёздочка забирает ещё один символ текста, сравнение продолжается с того же
                // места шаблона.
                p = starP + 1;
                t = ++starT;
            }
            else return false;
        }

        // Текст кончился — хвост шаблона допустим только если он весь из звёздочек (каждая может
        // подставить пустую строку).
        while (p < pattern.Length && pattern[p] == Wildcard) p++;
        return p == pattern.Length;
    }

    /// <summary>Регистронезависимое сравнение символов. ToUpperInvariant, а не CurrentCulture: теги
    /// хранятся и сравниваются инвариантно во всём остальном коде (см. TagString/Database.Search),
    /// и для кириллицы этого достаточно.</summary>
    private static bool SameChar(char a, char b) =>
        a == b || char.ToUpperInvariant(a) == char.ToUpperInvariant(b);
}
