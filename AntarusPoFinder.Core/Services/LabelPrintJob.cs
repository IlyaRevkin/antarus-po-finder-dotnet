namespace AntarusPoFinder.Core.Services;

/// <summary>Лист, который надо заказать у драйвера под эту наклейку: её физический размер, ни больше
/// ни меньше.</summary>
/// <param name="WidthMm">Ширина листа задания.</param>
/// <param name="HeightMm">Высота листа задания.</param>
public readonly record struct LabelSheet(double WidthMm, double HeightMm)
{
    /// <summary>Аппаратно-независимые единицы WPF (1/96 дюйма) — в них задаётся размер бумаги в
    /// PrintTicket.</summary>
    public double WidthDiu => WidthMm * 96.0 / 25.4;
    public double HeightDiu => HeightMm * 96.0 / 25.4;

    /// <summary>Микрометры — в них размер бумаги записан в самой схеме печати (Print Schema), и
    /// именно это число уходит драйверу. Целое: дробных микрон схема не знает.</summary>
    public int WidthMicrons => (int)Math.Round(WidthMm * 1000);
    public int HeightMicrons => (int)Math.Round(HeightMm * 1000);
}

/// <summary>Чем задание печати этикетки отличается от «просто напечатать визуал».
///
/// <b>Жалоба, ради которой это появилось:</b> «на некоторых принтерах печатает лишнюю одну пустую».
///
/// <b>Настоящая причина.</b> Этикетка собирается визуалом ровно в размер наклейки, и WPF отдаёт её
/// одной-единственной страницей этого размера — это проверено: сериализация PrintVisual даёт один
/// FixedPage 97.5 × 72 мм. А вот РАЗМЕР ЛИСТА заданию никто не задавал: PrintDialog брал тикет
/// очереди как есть, то есть тот лист, что стоит у принтера (на стенде драйвер отвечал A4/A5 при
/// наклейке 97.5 × 72). Дальше это расходится по типу драйвера: принтеры с драйвером XPS печатают
/// страницу документа как есть (проверено на «Microsoft Print to PDF» — один лист 97.5 × 72 мм), а
/// принтеры со старым драйвером GDI получают страницу документа НАЛОЖЕННОЙ на лист из тикета, и
/// страница, не помещающаяся в печатаемую область листа, раскладывается на несколько листов. Отсюда
/// и «на некоторых»: лишнюю наклейку выдают ровно те, у кого лист в драйвере не совпадает с наклейкой.
///
/// Вторым источником того же «лишнего» был чужой тикет: печать паспорта и инструкции (см.
/// DuplexPrinting) кладёт в тикет ОЧЕРЕДИ двустороннюю печать и две страницы на лист и возвращает их
/// обратно только после того, как очередь опустеет, — до трёх минут. Этикетка, напечатанная в это
/// окно, наследовала и дуплекс, и 2-up, и число копий.
///
/// <b>Что делаем.</b> Задание на этикетку описывается целиком, а не «чем получится»: лист ровно в
/// наклейку, одна копия, одна страница на лист, односторонняя, масштаб 100 %. Тогда страница
/// документа и физический лист — один и тот же прямоугольник, и делить нечего.</summary>
public static class LabelPrintJob
{
    /// <summary>Страниц в задании на одну этикетку. Ровно одна — и это не «так получилось», а
    /// требование: вторая страница физически означает вторую наклейку из рулона.</summary>
    public const int Pages = 1;

    /// <summary>Лист под эту наклейку. Поворот содержимого лист НЕ меняет: наклейку режет высечка,
    /// и её физический размер от того, как мы разложили текст, не зависит (см.
    /// <see cref="LabelLayout.ForDesign"/> — там переворачивается только компоновка).</summary>
    public static LabelSheet SheetFor(LabelLayout layout)
    {
        var v = layout.Clamped();
        return new LabelSheet(v.WidthMm, v.HeightMm);
    }

    /// <summary>Помещается ли всё, что рисуется, в заказанный лист. Главный инвариант против лишней
    /// страницы: визуал этикетки — это её страница целиком, и торчать за лист ему нечем.</summary>
    public static bool VisualFitsSheet(LabelLayout layout)
    {
        var sheet = SheetFor(layout);
        var page = LabelPlanner.Plan(layout, "Заголовок", "Подзаголовок", "ссылка").Page;

        // Раскладка ведётся на перевёрнутой стороне, если макет повёрнут: сравнивать надо с тем же
        // прямоугольником, только развёрнутым.
        var (w, h) = layout.Clamped().Rotation == LabelRotation.None
            ? (sheet.WidthMm, sheet.HeightMm)
            : (sheet.HeightMm, sheet.WidthMm);

        return page.W <= w + 0.01 && page.H <= h + 0.01;
    }
}
