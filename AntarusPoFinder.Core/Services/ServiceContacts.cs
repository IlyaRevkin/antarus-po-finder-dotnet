namespace AntarusPoFinder.Core.Services;

/// <summary>Контакты сервисной службы ANTARUS — ОДНО место на всю программу.
///
/// Эти строки печатаются на страницах-заглушках вместо инструкции и рядом с ней (см.
/// <see cref="StubKind"/>), то есть уезжают на хостинг и попадают заказчику на телефон. Меняются они
/// редко, но когда меняются — меняется телефон, а не смысл, и правка обязана быть в одной точке:
/// три макета с тремя переписанными вручную телефонами разъезжаются на первом же изменении, причём
/// незаметно — расхождение видно только на уже наклеенном шкафу.
///
/// Здесь лежат ЗНАЧЕНИЯ ПО УМОЛЧАНИЮ. Готовый текст блока собирает <see cref="Block"/>, а человек
/// может переписать его целиком в редакторе макета (настройка общая, см.
/// <see cref="StubLayoutSet.ServiceContacts"/>) — на случай, когда телефон поменялся, а обновление
/// программы ещё не доехало.</summary>
public static class ServiceContacts
{
    /// <summary>Бесплатный по России, круглосуточно.</summary>
    public const string Phone = "8 (800) 775-08-89";

    /// <summary>Ящик именно СЕРВИСНОЙ службы. Не путать с общим ящиком юрлица.</summary>
    public const string Email = "support@elitacompany.ru";

    public const string Site = "https://antarus.su/contacts";

    /// <summary>Готовый блок контактов, который подставляется в макеты вместо
    /// <see cref="StubLayout.ServicePlaceholder"/>.
    ///
    /// <b>Строки тут не просто перечисление — у каждой своя роль, и страница рисует их по-разному:</b>
    /// первая идёт подписью, вторая — КРУПНО (это номер, ради которого страница и существует),
    /// остальные мелко. Поэтому номер стоит отдельной строкой, а не в одной с условиями звонка:
    /// иначе его нечем выделить. Тот же разбор применяется и к блоку, переписанному человеком
    /// вручную, — см. InstructionStubWriter.DrawContactsPanel.</summary>
    public static string Block =>
        Label + "\n" +
        Phone + "\n" +
        Note + "\n" +
        $"{Email} · {Site.Replace("https://", "")}";

    /// <summary>Первая строка блока — подпись «чья это служба».</summary>
    public const string Label = "СЕРВИСНАЯ СЛУЖБА ANTARUS";

    /// <summary>Третья строка — условия звонка. Отдельно от номера: номер набирают, а это читают.</summary>
    public const string Note = "бесплатно по России, круглосуточно";
}
