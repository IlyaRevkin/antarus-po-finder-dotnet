using System.IO;

namespace AntarusPoFinder.Core.Services;

/// <summary>Откуда берётся папка обновлений на КОНКРЕТНОЙ машине. Правил всего три, и они решают
/// старый спор «настройка per-machine или синхронизируемая»:
///
/// 1. <b>app_update_path</b> (per-machine, как и был — в ConfigSyncService.SkipSettingsKeys) —
///    если он заполнен, побеждает он. Это ручной перебив: машина, у которой общий путь по каким-то
///    причинам не работает (своя буква диска, локальная копия обновлений, тестовая сборка), всегда
///    может задать себе свой и не зависеть от того, что придёт по синхронизации.
/// 2. <b>app_update_path_shared</b> (синхронизируемая настройка) — путь, который администратор
///    задаёт ОДИН раз, и он уезжает на все машины вместе с общим конфигом. Ради этого ключ и
///    появился: под будущее ограничение исходящих соединений по IP (GitHub из белого списка почти
///    наверняка выпадет — у него нет фиксированного набора адресов) обновления обязаны ходить из
///    сетевой папки, а обходить руками каждый компьютер — ровно то, чего синхронизация настроек
///    существует чтобы не делать.
/// 3. Ничего не задано — пусто, то есть обновления берутся с GitHub, как и раньше.
///
/// <b>Про разные буквы дисков</b> (главный аргумент против синхронизации такого пути). Он снимается
/// тем, что ОТНОСИТЕЛЬНЫЙ общий путь («Обновления», «Служебное\Обновления») разворачивается от
/// root_path ЭТОЙ машины — а root_path per-machine и у каждого свой. Это тот же приём, что и в
/// <see cref="FirmwarePathLocalizer"/> (взять машинно-независимый «хвост» и подставить свой корень),
/// но сам FirmwarePathLocalizer здесь неприменим напрямую: он опознаёт хвост по якорным папкам
/// «ПО»/«Параметры», а папка обновлений лежит не под ними и якоря не содержит. Поэтому — своё,
/// маленькое правило: относительный путь = «от корня рабочего диска».
///
/// UNC-путь (\\сервер\шара\...) одинаков на всех машинах и берётся как есть. Абсолютный путь с
/// буквой диска тоже берётся как есть — и это единственный случай, когда общая настройка может не
/// подойти конкретной машине; тогда на ней заполняют локальный перебив (правило 1), а
/// «Состояние подключения» покажет, что общая папка недоступна, вместо тихого молчания.</summary>
public static class UpdateFolderResolver
{
    /// <summary>Возвращает путь к папке обновлений для этой машины или пустую строку, если папка не
    /// настроена (тогда источник — GitHub). Диск/сеть не трогает: это чистая функция над тремя
    /// строками, доступность папки проверяется отдельно (см. AppUpdateService).</summary>
    public static string Resolve(string? localPath, string? sharedPath, string? rootPath)
    {
        var local = (localPath ?? "").Trim();
        if (local.Length > 0) return local;

        var shared = (sharedPath ?? "").Trim();
        if (shared.Length == 0) return "";

        if (!IsRelative(shared)) return shared;

        var root = (rootPath ?? "").Trim();
        // Относительный общий путь без известного корня развернуть не от чего — возвращаем пусто
        // (то есть «папка не настроена»), а не половину пути: подставленный от текущего каталога
        // процесса путь указывал бы в никуда и выглядел бы как настроенная, но битая папка.
        if (root.Length == 0) return "";

        // «.\Обновления» и «Обновления» — одно и то же; ведущий «.\» убираем, чтобы в настройках и в
        // отчёте «Состояние подключения» путь выглядел нормально, а не как «Z:\...\.\Обновления».
        var tail = shared;
        if (tail.StartsWith("./", StringComparison.Ordinal) || tail.StartsWith(@".\", StringComparison.Ordinal))
            tail = tail[2..];
        return Path.Combine(root, tail.TrimStart('\\', '/'));
    }

    /// <summary>Относительный = не UNC (\\сервер\шара), не «C:\...», не «\от корня диска».
    /// Отдельно опознаётся явная форма «.\Обновления» — её пишут по привычке, и она означает ровно
    /// то же самое.</summary>
    private static bool IsRelative(string path)
    {
        if (path.StartsWith(@"\\", StringComparison.Ordinal)) return false;
        if (path.StartsWith("./", StringComparison.Ordinal) || path.StartsWith(@".\", StringComparison.Ordinal)) return true;
        return !Path.IsPathRooted(path);
    }
}
