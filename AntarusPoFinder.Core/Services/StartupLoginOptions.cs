namespace AntarusPoFinder.Core.Services;

/// <summary>Какие способы входа предъявляет стартовое окно входа (<c>AdStartupLoginDialog</c>) при
/// заданном способе входа. Вынесено из окна в Core, чтобы ГЛАВНЫЙ инвариант — «корпоративный вход
/// (Keycloak/OIDC) НЕ запирает: вход по доменной учётной записи и аварийный пароль администратора
/// остаются доступны всегда, в том числе когда сервер Keycloak не отвечает» — можно было закрепить
/// тестом, не поднимая WPF.
///
/// Зачем это важно с версии 1.63: теперь способ входа (ad_auth_mode) синхронизируется между машинами
/// (см. ConfigSyncService.SkipSettingsKeys). Значит режим «oidc» может прилететь на машину, у которой
/// Keycloak в этот момент недоступен (нет сети, поднимается IPsec, сервер лёг). Если бы в режиме oidc
/// вход по AD был спрятан навсегда, такая машина осталась бы с одним аварийным паролём — тупик.
/// Поэтому порядок: Keycloak → при недоступности вход по доменной учётной записи → аварийный пароль.</summary>
public static class StartupLoginOptions
{
    /// <summary>Показывать ли панель корпоративного входа (Keycloak/OIDC) как ОСНОВНОЙ способ:
    /// только когда способ входа = oidc И его параметры заполнены (иначе входить им нечем, и окно
    /// молча оставляет обычный вход по AD).</summary>
    public static bool ShowCorporateLogin(string? authMode, bool oidcConfigured) =>
        authMode == "oidc" && oidcConfigured;

    /// <summary>Доступен ли вход по доменной учётной записи (логин/пароль AD) как запасной путь.
    /// Доступен ВСЕГДА, во всех режимах, включая oidc — при недоступном Keycloak это единственный,
    /// кроме аварийного пароля администратора, способ войти. В режиме oidc он лишь свёрнут по
    /// умолчанию (корпоративный вход основной) и раскрывается кнопкой или автоматически при
    /// недоступности сервера входа — но убрать его нельзя ни в одном режиме.</summary>
    public static bool AdFallbackAvailable(string? authMode, bool oidcConfigured) => true;

    /// <summary>Свёрнут ли изначально запасной вход по AD. В режиме oidc — да (чтобы не спорить с
    /// основным корпоративным входом); в остальных режимах вход по AD сам является основным способом
    /// и показан сразу.</summary>
    public static bool AdFallbackCollapsedInitially(string? authMode, bool oidcConfigured) =>
        ShowCorporateLogin(authMode, oidcConfigured);
}
