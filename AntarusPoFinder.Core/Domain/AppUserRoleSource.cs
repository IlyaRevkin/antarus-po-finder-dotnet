namespace AntarusPoFinder.Core.Domain;

/// <summary>ОТКУДА у строки ростера взялась её роль.
///
/// <b>Зачем это поле.</b> Жалоба Ильи повторялась дважды и обе формулировки — про одно: «не все
/// авторизованные пользователи отображаются во вкладке „Пользователи", и если даже отображается,
/// не у всех верная роль». По прежней таблице ответить на «почему роль не та» было нечем: в ней
/// лежало только КАКАЯ роль, а роль туда могла попасть тремя разными путями, и лечатся эти три
/// случая по-разному:
/// <list type="bullet">
/// <item><see cref="FirstLogin"/> — человек просто вошёл, ни одна настроенная AD-группа не
///   совпала, и ему выдали минимальную роль по умолчанию. Это не «сломалось», это «группу для него
///   никто не завёл»;</item>
/// <item><see cref="Manual"/> — роль поставил администратор руками в «Пользователях». Такую
///   сверка с доменом не должна молча затирать без объяснения, что именно поменялось;</item>
/// <item><see cref="Domain"/> — роль пришла из членства в настроенной AD-группе (вход по группе
///   или кнопка «Обновить из домена»). Это и есть правда, с которой всё сверяется;</item>
/// <item><see cref="Unknown"/> (пустая строка) — запись старше этого поля либо приехала
///   синхронизацией с машины, где приложение о поле ещё не знает. Честно показываем «неизвестно»,
///   а не выдумываем источник задним числом.</item>
/// </list></summary>
public static class AppUserRoleSource
{
    public const string Unknown = "";
    public const string FirstLogin = "login";
    public const string Manual = "manual";
    public const string Domain = "domain";

    /// <summary>Короткая подпись для столбца «Откуда роль». Если запись сверяли с доменом и не
    /// нашли ни в одной настроенной группе — это дописывается прямо сюда: администратору важнее
    /// всего именно этот случай («в списке есть, а в домене его нет»), и прятать его во всплывающую
    /// подсказку значит снова заставить гадать.</summary>
    public static string Label(AppUser user)
    {
        var baseLabel = user.RoleSource switch
        {
            Domain => "Из домена",
            Manual => "Вручную",
            FirstLogin => "С первого входа",
            _ => "Неизвестно",
        };
        var checkedEver = !string.IsNullOrEmpty(user.DomainCheckedAt);
        if (checkedEver && !user.DomainFound) return baseLabel + " · в домене не найден";
        return baseLabel;
    }

    /// <summary>Подпись для столбца «Сверка с доменом»: когда последний раз перечисляли состав
    /// настроенных групп и чем это кончилось для ЭТОЙ строки. Пусто — не сверяли ни разу (кнопкой
    /// «Обновить из домена» ещё не пользовались, либо запись появилась позже последней сверки).</summary>
    public static string CheckLabel(AppUser user)
    {
        if (string.IsNullOrEmpty(user.DomainCheckedAt)) return "не сверялась";
        return user.DomainFound ? $"{user.DomainCheckedAt} — в группе" : $"{user.DomainCheckedAt} — не найден";
    }
}
