namespace AntarusPoFinder.Core.Domain;

/// <summary>ИСПОЛНЕНИЕ прошивки (столбец fw_versions.execution) — короткая пометка вида
/// «3 насоса», «ПЧ Danfoss», «без АВР».
///
/// Зачем понадобилось. У одного «тип + подтип + контроллер» бывает несколько ОДНОВРЕМЕННО актуальных
/// прошивок, отличающихся не возрастом, а исполнением: в одной по умолчанию выбран один тип
/// частотников, в другой другое количество насосов. Раньше такая пара вела себя как обычная линейка —
/// свежая версия считалась заменой предыдущей, выдача схлопывала их в одну строку, и вторая прошивка
/// пропадала с глаз (просьба Ильи «должна быть возможность сделать несколько прошивок актуальных для
/// одного типа и подтипа»).
///
/// Почему это ОТДЕЛЬНОЕ поле, а не то, что уже было:
///   • <c>config_name</c> (FirmwareConfigService) — это вариант ОДНОЙ И ТОЙ ЖЕ прошивки: те же файлы,
///     тот же disk_path, отличается только набор тегов. Здесь же прошивки РАЗНЫЕ — свои файлы, своя
///     папка, свой номер; и строки-конфигурации намеренно не показываются ни в истории, ни в
///     модерации (Database.NotConfig), а эти показываться обязаны.
///   • <c>launch_types</c> — закрытый справочник типов ПУСКА (прямой, звезда-треугольник, ПЧ…).
///     «Сколько насосов» и «чей частотник» туда не ложатся, а расширять справочник пуска чужими
///     значениями означало бы сломать фильтр поиска по типу пуска.
///   • <c>hw_version</c> (модификация контроллера) — про ЖЕЛЕЗО контроллера, третья цифра номера
///     версии. Исполнение шкафа к плате контроллера отношения не имеет.
///   • теги — свободный текст, который вдобавок НАСЛЕДУЕТСЯ следующей версией
///     (FirmwareUploadService.PreviousVersionTags): признак, по которому версии делятся на линейки,
///     не может жить в списке, который сам себя копирует из соседней линейки.
///
/// Пустое значение — обычная прошивка, ровно прежнее поведение. Всё, что построено на исполнении
/// (схлопывание выдачи, «эту версию уже сменила более свежая», метка «Текущая»), для пустого
/// исполнения работает в точности как до его появления.
///
/// ⚠️ Сравнение — ВСЕГДА точное, без игнора регистра. В SQLite сравнение идёт по байтам
/// (COLLATE NOCASE сворачивает только латиницу, см. CLAUDE.md), и если .NET-сторона начнёт
/// сворачивать регистр по-своему, «ПЧ» и «пч» окажутся одним исполнением в выдаче и разными в
/// запросах NotSuperseded — ровно то расхождение, на котором уже обжигались. Вместо игнора регистра
/// значение нормализуется при ВВОДЕ (<see cref="Normalize"/>), а в форме предлагается списком уже
/// заведённых исполнений, чтобы одно и то же не набирали двумя способами.</summary>
public static class FwExecution
{
    /// <summary>Приведение к каноническому виду: обрезаны края, внутренние пробельные последовательности
    /// схлопнуты в один пробел. Больше ничего — регистр и сами слова принадлежат человеку.</summary>
    public static string Normalize(string? value)
    {
        if (string.IsNullOrWhiteSpace(value)) return "";
        var parts = value.Split((char[]?)null, System.StringSplitOptions.RemoveEmptyEntries);
        return string.Join(" ", parts);
    }

    /// <summary>Как исполнение называется в подписях: «основное» у пустого значения. Пустая строка в
    /// интерфейсе читалась бы как «поле не заполнили», хотя это полноправное состояние — обычная
    /// прошивка без деления на исполнения.</summary>
    public const string MainDisplayName = "основное";

    public static string Display(string? value) =>
        Normalize(value) is { Length: > 0 } s ? s : MainDisplayName;
}
