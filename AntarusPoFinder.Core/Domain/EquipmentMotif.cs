namespace AntarusPoFinder.Core.Domain;

/// <summary>Чем рисовать ход загрузки для этого шкафа.
///
/// Просьба Ильи (бета 2.0): «так как у нас компания делает насосные станции блочные тепловые пункты
/// КНС и тп, можно как-то добавить стилизацию, к примеру загрузку прошивки полосу у нгр кпч
/// отображать как насосную станцию что-нибудь продумать по дизайну, КНС как будто качает из
/// канализации и тп».
///
/// Суть не в украшении. Заливка идёт минуты, и всё это время на экране полоса, по которой не видно
/// НИЧЕГО, кроме процента: в какой шкаф льём, не перепутали ли. Мотив отвечает на это боковым
/// зрением — наладчик видит, что качается вода, а не стоки, и что это станция, а не тепловой пункт.
///
/// Выводится из НАЗВАНИЙ (тип шкафа и подтип), а не из отдельной настройки: справочник пополняет
/// администратор, и заставлять его при каждом новом подтипе выбирать ещё и картинку — верный способ
/// получить пустое поле. Незнакомое название даёт <see cref="Neutral"/> — обычную полосу, ровно как
/// было.</summary>
public enum EquipmentMotif
{
    /// <summary>Ничего особенного — обычная полоса. Так же выглядит всё, чего мы не узнали.</summary>
    Neutral,

    /// <summary>Насосная станция: вода идёт снизу вверх, к напору.</summary>
    PumpStation,

    /// <summary>Канализационная насосная: качает из приёмного резервуара, уровень в нём падает.</summary>
    Sewage,

    /// <summary>Блочный тепловой пункт: греющий контур, тепло идёт по кругу.</summary>
    HeatPoint,

    /// <summary>Шкаф управления задвижкой/заслонкой: створка открывается.</summary>
    Valve,
}

public static class EquipmentMotifResolver
{
    /// <summary>Мотив по названиям из справочника.
    ///
    /// Разбор по вхождению, а не по точному равенству: подтипы в справочнике называются живыми
    /// руками («КНС», «КНС-2», «КПЧ ПИ»), и требовать точного совпадения означало бы, что мотив
    /// пропадает от одной добавленной цифры.
    ///
    /// Порядок проверок важен: «КНС» должно сработать раньше общего «насос», иначе канализационная
    /// станция нарисуется как обычная.</summary>
    public static EquipmentMotif For(string? groupName, string? subtypeName)
    {
        var text = $"{groupName} {subtypeName}".Trim().ToUpperInvariant();
        if (text.Length == 0) return EquipmentMotif.Neutral;

        // КНС — канализационная насосная станция. Отдельно и первой: это тоже насосы, и общее
        // правило ниже увело бы её в обычную станцию.
        if (text.Contains("КНС")) return EquipmentMotif.Sewage;

        // ТГР — тепловые пункты; рядом живут и прямые слова, которыми их называют в справочнике.
        if (text.Contains("ТГР") || text.Contains("БТП") || text.Contains("ИТП") || text.Contains("ТЕПЛО"))
            return EquipmentMotif.HeatPoint;

        // НГР — насосные группы, ПЖ — пожарные насосные: и те и другие качают воду.
        if (text.Contains("НГР") || text.Contains("ПЖ") || text.Contains("НАСОС") || text.Contains("КПЧ"))
            return EquipmentMotif.PumpStation;

        if (text.Contains("ЗАДВИЖ") || text.Contains("ШУЗ")) return EquipmentMotif.Valve;

        return EquipmentMotif.Neutral;
    }

    /// <summary>Подпись под полосой: что именно происходит, словами. Нужна потому, что картинку
    /// боковым зрением можно и не прочитать, а ошибиться шкафом дорого.</summary>
    public static string Caption(EquipmentMotif motif) => motif switch
    {
        EquipmentMotif.PumpStation => "насосная станция",
        EquipmentMotif.Sewage => "канализационная насосная",
        EquipmentMotif.HeatPoint => "тепловой пункт",
        EquipmentMotif.Valve => "шкаф управления задвижкой",
        _ => "",
    };
}
