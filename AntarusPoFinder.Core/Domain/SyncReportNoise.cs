namespace AntarusPoFinder.Core.Domain;

/// <summary>ЧТО ИЗ ИТОГОВ СИНХРОНИЗАЦИИ — СОБЫТИЕ, А ЧТО ЛОГ.
///
/// Жалоба Ильи 15.10.2026: «получать уведомление что синхра была и получено 0 изменений не нужно,
/// это лог а не уведомление».
///
/// Почему это важнее, чем кажется. В программе любое сообщение строки состояния попадает в
/// колокольчик, а оттуда — письмом на почту (NotificationCenter.MirrorToEmail). Синхронизация идёт
/// по таймеру и почти всегда заканчивается ничем: это нормальная её работа, а не новость. Каждое
/// такое «получено 0» занимает строку в журнале и письмо в ящике — и ровно из-за этого перестают
/// читать весь журнал целиком, включая те сообщения, ради которых он заведён.
///
/// Правило простое: СОБЫТИЕ — это когда что-то изменилось или что-то не получилось. Всё остальное
/// показывается в строке состояния и исчезает вместе с ней.
///
/// Отдельным классом в Core, а не условием в обработчике, потому что мест, где подводится итог
/// синхронизации, несколько, и разъехаться они не должны.</summary>
public static class SyncReportNoise
{
    /// <summary>Стоит ли записывать итог в журнал уведомлений (и, значит, слать почтой).
    ///
    /// <paramref name="changes"/> — изменений в справочнике, <paramref name="settingsApplied"/> —
    /// применённых настроек, <paramref name="conflicts"/> — конфликтов, требующих решения,
    /// <paramref name="skipped"/> — записей, которые приём НЕ принял (их всегда надо называть: это
    /// и есть «у меня прошивка есть, а у остальных её нет»).</summary>
    public static bool Worth(int changes, int settingsApplied, int conflicts = 0, int skipped = 0) =>
        changes > 0 || settingsApplied > 0 || conflicts > 0 || skipped > 0;

    /// <summary>Текст итога. Когда ничего не произошло — короткая фраза без чисел: числа здесь
    /// только создают ощущение, что что-то случилось.</summary>
    public static string Describe(int changes, int settingsApplied) =>
        Worth(changes, settingsApplied)
            ? $"Конфиг обновлён: настроек {settingsApplied}, изменений {changes}"
            : "Изменений нет — всё уже совпадает";
}
