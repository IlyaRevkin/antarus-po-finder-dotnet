namespace AntarusPoFinder.Core.Domain;

/// <summary>Как прошивка подписывается в тикете о баге.
///
/// Слепок на момент жалобы, а не ссылка: тикет уезжает на машины, где этой прошивки может не быть
/// вовсе (ещё не синхронизировались, или запись удалили). Без подписи там осталась бы жалоба
/// неизвестно на что, и разбираться пришлось бы словами мимо программы — ровно то, от чего жучок
/// на карточке и заводился.
///
/// Подпись НЕ обновляется вслед за переименованием прошивки намеренно: она должна совпадать с тем,
/// что человек видел на экране, когда нажимал жучка. Иначе тикет «в НГР 2.0 не запускается насос»
/// через месяц превратился бы в тикет про КПЧ, и спорить о том, что имелось в виду, стало бы не с
/// чем — та же беда, что и со ссылкой по локальному id.</summary>
public static class FwBugLabel
{
    public static string Build(string name, string versionRaw, string execution)
    {
        var head = string.Join(" ", new[] { (name ?? "").Trim(), (versionRaw ?? "").Trim() }
            .Where(p => p.Length > 0));
        var exec = (execution ?? "").Trim();
        if (head.Length == 0) return exec.Length == 0 ? "" : exec;
        return exec.Length == 0 ? head : $"{head} ({exec})";
    }
}
