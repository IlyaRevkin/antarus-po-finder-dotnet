namespace AntarusPoFinder.Core.Domain;

/// <summary>ОДИН СЕАНС РАБОТЫ ПРОГРАММЫ: кто, с какой машины, под какой версией.
///
/// <b>Зачем это поверх «Подключений».</b> Таблица sync_participants (Database.SyncParticipants)
/// отвечает на вопрос «какая версия у этой УСТАНОВКИ» — строка в ней одна на копию программы и
/// переписывается при каждом обмене. Этого хватало, пока вопрос был «кого пнуть обновиться», и не
/// хватает теперь: просьба Ильи — «чтобы я мог управлять сессиями всеми через него… так можно будет
/// убивать старые версии или те кто мусор записывают». Убивать надо не установку, а конкретный
/// запущенный экземпляр: под одной установкой за день сменяются двое, и завершать надо тот сеанс,
/// который пишет мусор прямо сейчас, а не «машину вообще».
///
/// Поэтому ключ здесь — <see cref="SessionId"/>, новый GUID на КАЖДЫЙ запуск программы, а не
/// origin_id установки. Строки накапливаются: закрытый сеанс остаётся историей («кто работал
/// вчера»), а не исчезает.
///
/// <b>Почему ничего не удаляется.</b> Синхронизация конфига в этом приложении НЕ переносит удаления
/// (осознанное ограничение, записано в CLAUDE.md): удалённая строка просто приедет обратно с чужой
/// машины. Поэтому «завершить сеанс» — это не DELETE, а ДОПИСАННОЕ ПОЛЕ (<see cref="EndedAt"/>):
/// добавление, а не удаление, и оно едет общим конфигом так же надёжно, как любая другая запись.
/// Подробнее про слияние — в <see cref="AntarusPoFinder.Core.Services.AppSessions.Merge"/>.</summary>
public class AppSession
{
    /// <summary>GUID этого ЗАПУСКА программы. Первичный ключ и единственное, по чему сеанс
    /// опознаётся на всех машинах.</summary>
    public string SessionId { get; set; } = "";

    /// <summary>GUID установки — тот же, что у «Подключений» (Database.UsageOriginId). Нужен,
    /// чтобы программа на своей машине узнала СВОИ прежние сеансы, даже если про session_id уже
    /// забыла (перезапуск после падения).</summary>
    public string OriginId { get; set; } = "";

    public string MachineName { get; set; } = "";

    /// <summary>Нормализованный AD-логин того, кто работает (AppUserAuthService.NormalizeAdLogin),
    /// либо имя учётки Windows — ровно то же «кто сейчас действует», что пишется в CreatedBy
    /// (AppServices.CurrentUserName). По нему же решается, свой это сеанс или чужой.</summary>
    public string UserLogin { get; set; } = "";

    public string AppVersion { get; set; } = "";

    /// <summary>«рабочая» или «бета» — как в «Подключениях».</summary>
    public string Channel { get; set; } = "";

    public string StartedAt { get; set; } = "";

    /// <summary>Когда сеанс в последний раз подал признаки жизни. Обновляется самой программой,
    /// пока она запущена (см. AppSessions.HeartbeatInterval).</summary>
    public string HeartbeatAt { get; set; } = "";

    /// <summary>Когда администратор ПОПРОСИЛ завершить сеанс. Пусто — не просил.
    ///
    /// Это просьба, а не факт выхода: программа на той машине увидит её при ближайшем тике и выйдет
    /// сама, дождавшись окончания долгой операции (см. AppSessions.ShutdownDelayReason — обрывать
    /// заливку в ПЛК нельзя, контроллер останется окирпиченным). Факт выхода — это
    /// <see cref="ClosedAt"/>.</summary>
    public string EndedAt { get; set; } = "";

    /// <summary>Кто попросил завершить — чтобы человеку на той машине было что сказать, а в списке
    /// было видно, чьё это решение.</summary>
    public string EndedBy { get; set; } = "";

    /// <summary>Когда программа действительно закрылась. Ставится самой программой — и при обычном
    /// выходе, и после выполненной просьбы завершить.</summary>
    public string ClosedAt { get; set; } = "";
}

/// <summary>Состояние сеанса — вычисляется, а не хранится: «живой» зависит от текущего времени, и
/// запомненный ответ разошёлся бы с ним в ту же минуту (та же причина, по которой состояние строки
/// в «Подключениях» считается на лету, см. SettingsView.ConnectionRow).</summary>
public enum AppSessionState
{
    /// <summary>Программа запущена и подаёт признаки жизни.</summary>
    Alive,

    /// <summary>Администратор попросил завершить, а сеанс ещё жив: та машина либо не дошла до
    /// ближайшего тика, либо ждёт окончания долгой операции.</summary>
    Ending,

    /// <summary>Программа вышла — сама или по просьбе администратора.</summary>
    Closed,

    /// <summary>Отметка протухла: программа не подавала признаков жизни дольше положенного.
    /// Показываем как завершённый, но ОТДЕЛЬНО от честно закрытого: разница — между «вышел» и
    /// «пропал» (закрыли по питанию, упала, увезли ноутбук).</summary>
    Stale,
}
