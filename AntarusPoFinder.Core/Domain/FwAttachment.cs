namespace AntarusPoFinder.Core.Domain;

/// <summary>Один ДОП. МАТЕРИАЛ версии прошивки — произвольный файл, который наладчику нужен рядом с
/// самой программой: краткое руководство по этому шкафу, описание специфики работы объекта, прошивка
/// ПЛК от поставщика (не наша, а внутренний алгоритм самого ПЛК) и всё прочее в таком духе.
///
/// Почему СПИСОК, а не ещё три поля в fw_versions рядом с картами и инструкцией: набор таких файлов
/// заранее не известен, и четвёртый по счёту вид не должен требовать нового релиза приложения. Вид
/// берётся из справочника (fw_attachment_kinds), а не из перечисления в коде, ровно по той же
/// причине — администратор заводит свой вид сам.
///
/// <see cref="DeletedAt"/> — тумбстоун, как у fw_versions: таблица аддитивная (у каждой машины бывают
/// свои вложения, которых не видела ни одна другая), поэтому «строки нет во входящем снимке» никогда
/// не означает «её удалили» — удаление приходится передавать положительным сигналом. См.
/// Database.FwAttachments.cs и секцию fw_attachments в Database.ConfigExchange.cs.</summary>
public class FwAttachment
{
    public int? Id { get; set; }
    public int FwVersionId { get; set; }

    /// <summary>Имя файла как его видит человек — сохраняется осмысленным (файл не переименовывается
    /// в «версия_что-то»), потому что его открывают и глазами ищут в папке.</summary>
    public string Filename { get; set; } = "";

    /// <summary>Полный путь к файлу на диске. Абсолютный и в нотации той машины, которая его клала, —
    /// у получателя приводится к своему корню (FirmwarePathLocalizer), как и остальные пути прошивки.</summary>
    public string DiskPath { get; set; } = "";

    /// <summary>Вид из справочника fw_attachment_kinds («Руководство наладчика», «Специфика работы»,
    /// «Прошивка ПЛК поставщика», «Прочее» — и всё, что администратор добавил сам). Хранится СТРОКОЙ,
    /// а не ссылкой на строку справочника: вид, удалённый из справочника позже, обязан остаться
    /// читаемым у уже приложенного файла (тот же приём, что у param_files.manufacturer).</summary>
    public string Kind { get; set; } = "";

    /// <summary>Произвольный комментарий: зачем этот файл и что в нём. Попадает в поиск по версии
    /// наравне с видом — «краткое руководство для наладчика» должно находиться словами (см.
    /// Database.Search.cs).</summary>
    public string Comment { get; set; } = "";

    public string AddedBy { get; set; } = "";
    public string AddedAt { get; set; } = "";

    /// <summary>Отметка удаления ('' — живое вложение). См. док класса.</summary>
    public string DeletedAt { get; set; } = "";

    /// <summary>Переносимый идентификатор строки — по нему синхронизация опознаёт «то же самое»
    /// вложение у соседа (см. sync_id у fw_versions/param_files, здесь он ровно того же назначения).</summary>
    public string SyncId { get; set; } = "";

    /// <summary>Когда строку последний раз правили — по этой отметке сводятся вид и комментарий при
    /// синхронизации (выигрывает более поздняя правка, а не тот, кто позже нажал импорт).</summary>
    public string UpdatedAt { get; set; } = "";
}

/// <summary>Виды доп. материалов, которыми справочник заполняется при первом запуске. Дальше список
/// живёт в БД (fw_attachment_kinds) и правится людьми — здесь только стартовый набор, согласованный
/// с Ильёй.</summary>
public static class FwAttachmentKinds
{
    public const string SetupGuide = "Руководство наладчика";
    public const string WorkSpecifics = "Специфика работы";
    public const string VendorPlcFirmware = "Прошивка ПЛК поставщика";
    public const string Other = "Прочее";

    public static readonly string[] Defaults = { SetupGuide, WorkSpecifics, VendorPlcFirmware, Other };
}
