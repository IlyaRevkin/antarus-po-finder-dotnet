namespace AntarusPoFinder.Core.Domain;

/// <summary>КТО МЫ — СТАБИЛЬНАЯ ПРОГРАММА ИЛИ БЕТА.
///
/// Бета ставится ОТДЕЛЬНЫМ приложением, рядом со стабильным, а не поверх него. Прямая просьба Ильи:
/// «лучше сделать чтобы бета ставилась отдельным приложением чтобы если там что-то не то, то
/// работники смогли бы пользоваться предыдущей версией без необходимости переустановки и тп».
///
/// Из этого следует всё остальное:
/// <list type="bullet">
/// <item>своя папка установки и свой ярлык — иначе установщик затёр бы рабочую программу;</item>
/// <item>свой профиль в %LocalAppData% — иначе сломанная бета испортила бы рабочую базу, и «вернуться
///       на предыдущую версию» перестало бы помогать;</item>
/// <item>своя лента релизов (теги <c>beta-v…</c>, помеченные prerelease) — и, главное, стабильная
///       программа предварительные релизы НЕ ВИДИТ вовсе (см. AppUpdateService): иначе бета с
///       большим номером прилетела бы автообновлением на все рабочие машины.</item>
/// </list>
///
/// Переключается ОДНОЙ константой сборки <c>BETA</c> (см. AntarusPoFinder.App.csproj, конфигурация
/// Beta). Никаких проверок «а не бета ли мы» по имени файла или по настройке: настройку можно
/// случайно синхронизировать с чужой машины вместе с общим конфигом, и рабочая программа начала бы
/// считать себя бетой.</summary>
public static class AppIdentity
{
#if BETA
    public const bool IsBeta = true;
#else
    public const bool IsBeta = false;
#endif

    /// <summary>Приставка тега бета-релиза: <c>beta-v2.0.0.0</c>. Отдельная лента в том же
    /// репозитории — заводить второй репозиторий ради этого незачем, а спутать теги нельзя:
    /// стабильный канал отбрасывает всё с этой приставкой, бета — всё без неё.</summary>
    public const string BetaTagPrefix = "beta-";

    /// <summary>Название в заголовке окна, в ярлыке и в установщике. Бету обязано быть видно с
    /// первого взгляда: две одинаково названные программы в меню «Пуск» — это гарантированный
    /// вопрос «а какая из них рабочая».</summary>
    public static string ProductName => IsBeta ? "Antarus ПО Finder (бета)" : "Antarus ПО Finder";

    /// <summary>Имя папки профиля в %LocalAppData%. Разное у стабильной и беты намеренно: это и есть
    /// тот самый «откат без переустановки» — сломанная бета не трогает рабочую базу.</summary>
    public static string AppDataFolderName => IsBeta ? "AntarusPOFinderBeta" : "AntarusPOFinder";
}
