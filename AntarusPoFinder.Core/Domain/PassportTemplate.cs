namespace AntarusPoFinder.Core.Domain;

/// <summary>Шаблон паспорта шкафа — документ, который печатают и вкладывают в сам шкаф. От прошивки
/// и от файла параметров отличается тем, к ЧЕМУ он привязан: паспорт описывает ШКАФ (тип + подтип),
/// а не программу контроллера. Отсюда два случая, которые запись обязана покрывать одинаково:
///   • у шкафа есть и прошивка, и паспорт (ПЖ ПИ) — паспорт не должен быть вложением конкретной
///     версии прошивки, иначе при следующей перезаливке версии он «отвяжется» от шкафа;
///   • у шкафа нет прошивки вовсе, только паспорт — такой шкаф обязан находиться поиском, а
///     единственная запись о нём и есть паспорт.
///
/// Поэтому это самостоятельная таблица (passports), устроенная как param_files: подтип + имя как
/// натуральный ключ, свои теги для поиска, sync_id для синхронизации между машинами и архивация
/// вместо удаления (тумбстоун). Контроллер в ключ НЕ входит — паспорт один на шкаф, независимо от
/// того, какой ПЛК внутри.</summary>
public class PassportTemplate
{
    public int? Id { get; set; }
    public int? SubtypeId { get; set; }

    /// <summary>Название паспорта, как его вводит оператор («Паспорт ПЖ ПИ», «Шкаф пожаротушения
    /// 2 насоса»). Оно же — имя папки на диске (после чистки недопустимых символов, см.
    /// PassportService.FolderName) и вторая половина натурального ключа: у одного подтипа бывает
    /// несколько паспортов под разные исполнения шкафа. Пусто не бывает — форма загрузки
    /// подставляет имя файла без расширения.</summary>
    public string Name { get; set; } = "";

    /// <summary>Имя актуального файла паспорта в папке. Прежние редакции лежат рядом, в подпапке
    /// (см. ParamFileUploadService.ArchivePreviousOnDisk) — открывается всегда этот.</summary>
    public string Filename { get; set; } = "";

    /// <summary>Папка паспорта на диске: ПО\&lt;тип&gt;[\&lt;подтип&gt;]\Паспорт\&lt;название&gt;. Абсолютный путь
    /// машины-загрузчика — открывающая сторона приводит его к своему корню (FirmwarePathLocalizer).</summary>
    public string DiskPath { get; set; } = "";

    /// <summary>Журнал изменений: перезаливка дописывает сюда датированную строку (что и когда
    /// поменялось, куда убрана прежняя редакция) — ровно то же, что у файлов параметров.</summary>
    public string Description { get; set; } = "";

    public string UploadDate { get; set; } = "";
    public bool Archived { get; set; }
    public string Tags { get; set; } = "";

    /// <summary>Стабильный межмашинный идентификатор строки (GUID) — см. ParamFile.SyncId.</summary>
    public string SyncId { get; set; } = "";

    // Populated by joins for display purposes.
    public string SubtypeName { get; set; } = "";
    public string FolderName { get; set; } = "";
    public string GroupName { get; set; } = "";
}
