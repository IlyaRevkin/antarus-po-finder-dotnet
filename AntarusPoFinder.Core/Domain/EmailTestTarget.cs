namespace AntarusPoFinder.Core.Domain;

/// <summary>Куда уйдёт пробное письмо.
///
/// Жалоба Ильи: «я не могу тестовое письмо отправить конкретному email, надо добавить такой
/// функционал». Раньше адрес был жёстко равен «От кого» — то есть проверить можно было только то,
/// что сервер принимает письмо себе же. Самый частый вопрос при настройке («а до Иванова-то
/// дойдёт?») проверке не поддавался вовсе.
///
/// Решение вынесено из обработчика кнопки отдельной функцией ровно потому, что в нём три развилки
/// (пусто → себе; мусор → сказать словами; группа AD → адресом письма быть не может), и каждая из
/// них молча ломается при правке соседней.</summary>
/// <param name="Address">Адрес, на который слать. Пусто, если слать нельзя.</param>
/// <param name="Error">Человеческая причина отказа или пусто.</param>
/// <param name="ToSelf">true — адрес не вводили, письмо уходит на «От кого». Нужно, чтобы в ответе
/// честно сказать, куда именно ушло: «отправлено» без адреса и порождает вопрос «а куда?».</param>
public sealed record EmailTestTarget(string Address, string Error, bool ToSelf)
{
    public bool Ok => Error.Length == 0;

    public static EmailTestTarget Resolve(string? typed, string? from)
    {
        var target = (typed ?? "").Trim();
        var self = (from ?? "").Trim();

        if (target.Length == 0)
        {
            // Пусто — как было до появления поля: письмо себе. Прежнее поведение обязано остаться
            // поведением по умолчанию, иначе привычная кнопка начнёт требовать ввода.
            return self.Length == 0
                ? new EmailTestTarget("", "Укажите адрес «От кого» или впишите, кому отправить пробное письмо.", false)
                : EmailRouting.LooksLikeMailbox(self)
                    ? new EmailTestTarget(self, "", true)
                    : new EmailTestTarget("", $"Адрес «От кого» ({self}) не похож на почтовый ящик.", true);
        }

        if (!EmailRouting.LooksLikeMailbox(target))
            // Группа AD здесь не годится принципиально, а не из строгости: её раскрывает почтовый
            // сервер, и адресом одиночного письма она быть не может — см. EmailNotifier.Send.
            return new EmailTestTarget("", $"«{target}» не похож на почтовый ящик. Нужен конкретный адрес вида имя@домен — группу AD проверить письмом нельзя.", false);

        return new EmailTestTarget(target, "", false);
    }
}
