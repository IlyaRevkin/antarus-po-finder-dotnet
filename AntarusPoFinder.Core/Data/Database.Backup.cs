using System.IO;

namespace AntarusPoFinder.Core.Data;

public partial class Database
{
    /// <summary>СНЯТЬ КОПИЮ БАЗЫ В ОТДЕЛЬНЫЙ ФАЙЛ — единственный допустимый способ.
    ///
    /// Копировать po_finder.db файловым копированием из-под работающего приложения НЕЛЬЗЯ, и это не
    /// придирка. База открыта в режиме WAL (см. конструктор, PRAGMA journal_mode=WAL): часть уже
    /// подтверждённых изменений в этот момент физически лежит не в .db, а в соседнем .db-wal.
    /// Скопировав один .db, получаем файл, у которого пропали последние транзакции, а в худшем
    /// случае — порванный на середине страницы, то есть копию, которая выглядит как копия ровно до
    /// того дня, когда её попробуют открыть.
    ///
    /// VACUUM INTO (SQLite 3.27+, в Microsoft.Data.Sqlite есть) делает это правильно: читает базу в
    /// транзакции, то есть видит согласованное состояние вместе с WAL, и пишет в целевой файл уже
    /// упакованную, самодостаточную копию без WAL вовсе. Побочно она ещё и дефрагментирована —
    /// копия выходит меньше оригинала.
    ///
    /// Цель обязана НЕ СУЩЕСТВОВАТЬ: так требует сам VACUUM INTO (он откажется писать поверх), и это
    /// удачно — молча затереть вчерашнюю копию сегодняшней неудачной попыткой было бы худшим из
    /// возможных поведений для резервного копирования.
    ///
    /// Блокировок пишущим не ставит дольше обычного чтения, но на большой базе занимает секунды,
    /// поэтому вызывать только из фонового потока (см. BackupService).</summary>
    public void BackupTo(string targetPath)
    {
        var dir = Path.GetDirectoryName(targetPath);
        if (!string.IsNullOrEmpty(dir)) Directory.CreateDirectory(dir);
        if (File.Exists(targetPath))
            throw new IOException($"Файл копии уже существует: {targetPath}");

        using var cmd = _conn.CreateCommand();
        // Параметризуем: путь приходит из настройки, а склейка кавычек в SQL — это ровно тот способ
        // испортить себе резервную копию, от которого потом не отмоешься.
        cmd.CommandText = "VACUUM INTO @path";
        cmd.Parameters.AddWithValue("@path", targetPath);
        cmd.ExecuteNonQuery();
    }
}
