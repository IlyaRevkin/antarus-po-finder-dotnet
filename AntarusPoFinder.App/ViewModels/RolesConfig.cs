using System.Linq;

namespace AntarusPoFinder.App.ViewModels;

public static class RolesConfig
{
    /// <summary>Пункты бокового меню и блок, в котором каждый живёт (см. <see cref="NavSection"/>).
    /// Порядок — порядок кнопок внутри своего блока.
    ///
    /// РАСКЛАДКА 2.2 — ОНА ЖЕ ЕДИНСТВЕННАЯ. Замечания Ильи 16.10.2026: «все ещё висит пункт
    /// дополнительно который нужно было перенести», «для программиста перенеси загрузку прошивок
    /// а для наладчика вкладку осмотр». «Дополнительно» исчезло как секция, её пункты разошлись
    /// туда, где им место — «Хранилище» и «Тикеты» стали вкладками настроек (это сервисное, а не
    /// работа). «Загрузка ПО» ушла к программисту, «Осмотр» — к наладчику.
    ///
    /// До 2.2 здесь лежали ДВЕ раскладки — старая рабочая и бета-раскладка, выбираемые по
    /// AppIdentity.IsBeta: перестройка меню обкатывалась в бете, чтобы обычный релиз не принёс её
    /// всем недоделанной. Обкатка кончилась, раскладка выпущена, второго массива больше нет.</summary>
    private static readonly (string PageId, string Label, NavSection Section)[] AllNavItems =
    [
        ("search", "Поиск", NavSection.Main),
        // ДЛЯ НАЛАДЧИКА
        ("inspection", "Осмотр", NavSection.Setup),
        ("params", "Параметры ПЧ/УПП", NavSection.Setup),
        ("newversions", "Модерация прошивок", NavSection.Setup),
        // Мобильный доступ — у наладчика, потому что с телефоном у шкафа стоит он.
        ("mobile", "Мобильный доступ", NavSection.Setup),
        // ДЛЯ ПРОГРАММИСТА
        ("upload", "Загрузка ПО", NavSection.Dev),
        ("fwbugs", "Баги прошивок", NavSection.Dev),
        // «Тикеты» и «Хранилище» в боковом меню НЕ значатся: это сервисное, а не работа. Илья
        // 16.10.2026: «хранилище не должно быть у программиста», «тикеты это сервисное это убрать
        // надо в настройки». Обе страницы живут вкладками настроек (SettingsView), открываются
        // оттуда и по-прежнему доступны тем же ролям — см. RoleAccess ниже.
    ];

    public static (string PageId, string Label, NavSection Section)[] NavItems => NavItemsFor(Core.Domain.AppIdentity.IsBeta);

    /// <summary>Раскладка меню для конкретной сборки. Отличие у неё осталось ровно одно —
    /// «Мобильный доступ»: эта страница поднимает на машине слушателя локальной сети, живьём на
    /// объекте не проверена (docs/mobile-access-plan.md) и остаётся бета-функцией. В рабочей
    /// программе пункта нет, а значит нет и единственного входа на страницу.
    ///
    /// Параметр, а не чтение AppIdentity внутри: обе раскладки надо проверять независимо от того,
    /// в какой конфигурации собраны сами тесты.</summary>
    public static (string PageId, string Label, NavSection Section)[] NavItemsFor(bool beta) =>
        beta ? AllNavItems : AllNavItems.Where(n => n.PageId != "mobile").ToArray();

    /// <summary>Все три роли работают с одним и тем же общим диском, поэтому пути и интервал
    /// синхронизации (страница "network") доступны всем — не только администратору, который раньше
    /// был единственным, кто мог их настроить через полноценные Настройки. "tickets" (баг-репорты/
    /// предложения) точно так же доступна всем ролям — что именно каждая роль видит/может там
    /// делать решается внутри TicketsView (CreatedBy-фильтр для наладчика/программиста, полный
    /// доступ и смена статуса для администратора), не через видимость самого пункта меню.
    /// "settings" тоже теперь доступна наладчику/программисту — что именно из неё видно каждой роли
    /// решается внутри SettingsView (ApplyRoleVisibility: урезанный набор вкладок + урезанное
    /// "Общие"), не через видимость самого пункта меню, тем же способом что и "tickets".
    ///
    /// Страницы "cleanup" здесь больше нет: «Чистка диска» стала вкладкой Настроек. Она
    /// переименовывает, переносит и безвозвратно удаляет файлы на общем диске, то есть чужую работу,
    /// поэтому осталась строго администраторской — теперь это видимость вкладки
    /// (SettingsView.ApplyRoleVisibility), а не строка в этом справочнике.</summary>
    public static readonly Dictionary<string, HashSet<string>> RoleAccess = new()
    {
        // «hosting» — состояние выкладки на хостинг. Наладчику там делать нечего: он инструкции не
        // выкладывает, а читает их по QR. Программист выкладывает и обязан видеть, доехало ли.
        // «fwbugs» — страница багов прошивок. Наладчик заводит их жучком на карточке и видит на
        // общей странице «Тикеты», отдельный пункт ему не нужен; правит их программист.
        // «mobile» в списках у наладчика и администратора, но пунктом меню существует только в
        // бета-раскладке выше — в рабочей программе эта строка ни на что не влияет.
        ["naladchik"] = ["search", "inspection", "newversions", "params", "settings", "network", "tickets", "mobile"],
        ["programmer"] = ["search", "upload", "params", "settings", "network", "hosting", "tickets", "fwbugs"],
        ["administrator"] = ["search", "inspection", "newversions", "upload", "params", "settings", "network", "hosting", "tickets", "fwbugs", "mobile"],
    };

    public static readonly (string RoleId, string Label)[] Roles =
    [
        ("naladchik", "Наладчик"),
        ("programmer", "Программист"),
        ("administrator", "Администратор"),
    ];

    public static string RoleLabel(string roleId)
    {
        foreach (var (id, label) in Roles)
            if (id == roleId) return label;
        return roleId;
    }
}
