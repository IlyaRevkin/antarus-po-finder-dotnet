using System.IO;

namespace AntarusPoFinder.App.Services;

/// <summary>Один вопрос: дописан ли файл, который только что появился в папке.
///
/// Нужно это из-за решения по фотографиям осмотра (см. docs/mobile-access-plan.md, раздел 4):
/// телефон кладёт снимок прямо в сетевую папку по SMB, а программа видит его наблюдателем за
/// каталогом. Беда в том, что событие о появлении файла приходит в начале копирования, а не в
/// конце: по сети файл приезжает кусками, и в этот момент на диске лежит обрезанный JPEG. Открыть
/// его — получить половину снимка или ошибку чтения, причём ровно тогда, когда человек на него
/// нажал.
///
/// Вынесено из InspectionView отдельно, потому что это единственная часть подхвата, которую можно
/// проверить тестом без живой шары и без окна.</summary>
public static class IncomingFileProbe
{
    /// <summary>Длина файла, если его прямо сейчас никто не пишет, иначе null.
    ///
    /// Проверка — попыткой открыть файл БЕЗ общего доступа (<see cref="FileShare.None"/>): пока
    /// писатель держит свой дескриптор, открыть так не выйдет. Отказ по любой другой причине (нет
    /// прав, отвалилась шара, файл уже удалили) тоже даёт null — для вызывающего это одно и то же
    /// «пока не трогать», и различать причины ему незачем.
    ///
    /// ⚠️ Одной этой проверки для вывода «файл готов» МАЛО. Часть реализаций SMB не держит файл
    /// заблокированным между порциями записи, и в паузе он открывается как ни в чём не бывало.
    /// Поэтому вызывающий (InspectionView.PollIncoming) считает файл готовым, только когда длина
    /// совпала на двух подряд замерах.</summary>
    public static long? TryMeasureIfFree(string path)
    {
        try
        {
            using var stream = new FileStream(path, FileMode.Open, FileAccess.Read, FileShare.None);
            return stream.Length;
        }
        catch
        {
            return null;
        }
    }
}
