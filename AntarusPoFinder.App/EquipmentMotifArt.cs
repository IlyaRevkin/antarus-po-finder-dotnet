    public static (Geometry? From, Geometry? To) Scene(EquipmentMotif motif) => motif switch
    {
        // Насосная: насос гонит воду в напорную линию.
        EquipmentMotif.PumpStation => (Geometry.Parse(WaterPump), Geometry.Parse(WaterDrop)),
        // КНС: тот же насос, но качает из приёмника — знак воды слева.
        EquipmentMotif.Sewage => (Geometry.Parse(WaterDrop), Geometry.Parse(WaterPump)),
        // Тепловой пункт: тепловой насос греет контур.
