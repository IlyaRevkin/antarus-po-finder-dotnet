using System.Windows.Media;
using AntarusPoFinder.Core.Domain;

namespace AntarusPoFinder.App;

/// <summary>КАК МОТИВ ОБОРУДОВАНИЯ ВЫГЛЯДИТ: значок, цвет и характер движения.
///
/// Вынесено из окна загрузки, когда мотив понадобился во втором месте — в карточке выдачи. Две
/// копии одних и тех же геометрий разъехались бы при первой же правке, и «насос в поиске» перестал
/// бы совпадать с «насосом при заливке»: человек читает их как один и тот же знак, и расхождение
/// он заметит раньше, чем мы.
///
/// Цвета — КЛЮЧАМИ кистей темы, а не числами: приложение живёт в четырёх темах, и захардкоженный
/// синий в «Стекле» выглядел бы заплаткой. Тему к тому же могут переключить прямо во время
/// заливки.</summary>
public static class EquipmentMotifArt
{
    /// <summary>Ключ кисти темы для этого мотива.</summary>
    public static string BrushKey(EquipmentMotif motif) => motif switch
    {
        // Стоки — не питьевая вода, и цвет у них свой: на экране это первое, что отличает КНС от
        // обычной насосной, ещё до того, как прочитана подпись.
        EquipmentMotif.Sewage => "SuccessBrush",
        // Пожарный шкаф — оранжево-красный: «для пожарных можно чтобы в оранжево-красный
        // открывалось и заливалось и типа тушило пожар».
        EquipmentMotif.Fire => "FireBrush",
        EquipmentMotif.HeatPoint => "WarningBrush",
        EquipmentMotif.Valve => "CautionBrush",
        _ => "AccentBrush",
    };

    /// <summary>Значок мотива. Геометрии простые намеренно: это метка в 14–18 пикселей рядом с
    /// текстом, а не иллюстрация — в ней должно читаться одно: «это насос», «это тепло».</summary>
    public static Geometry Icon(EquipmentMotif motif) => Geometry.Parse(motif switch
    {
        // Пожарный шкаф: пламя. Заливкой, а не контуром — на 16 пикселях контурное пламя
        // читается как клякса.
        EquipmentMotif.Fire => "M12,2 C15,6 19,9 19,14 A7,7 0 0,1 5,14 C5,10 8,9 9,6 C10,9 12,9 12,9 C12,7 10,5 12,2 Z",
        // Насос: корпус-окружность и напорный патрубок вверх. Линий ровно три — на 16 пикселях
        // всё, что сложнее, сливается в пятно.
        EquipmentMotif.PumpStation => "M12,14 m-5,0 a5,5 0 1,0 10,0 a5,5 0 1,0 -10,0 M12,9 L12,4 L18,4",
        // Канализационная: тот же насос, но с подводящим лотком снизу — качает из приёмника.
        EquipmentMotif.Sewage => "M12,12 m-4,0 a4,4 0 1,0 8,0 a4,4 0 1,0 -8,0 M12,16 L12,20 M5,20 L19,20",
        // Тепловой пункт: две волны тепла.
        EquipmentMotif.HeatPoint => "M8,20 C8,16 12,15 12,11 C12,7 8,6 8,2 M16,20 C16,16 20,15 20,11 C20,7 16,6 16,2",
        // ЗАДВИЖКА — классический символ: «бабочка» из двух треугольников, шток и штурвал.
        // Прежний рисунок (прямоугольный корпус со штоком) при заливке в карточке выдачи читался
        // как бомба с фитилём — дословная жалоба Ильи «при поиске значок бомбы почему-то».
        _ => "M5,8 L5,16 L12,12 Z M19,8 L19,16 L12,12 Z M12,12 L12,5 M8,5 L16,5",
    });

    /// <summary>КАКИМ ДВИЖЕНИЕМ показывать ход заливки — метка для полосы (стиль FlowProgressBar).
    ///
    /// Просьба Ильи: «можно просто вентиль и что вода льётся из гидранта, качается, будто качают
    /// как через ручной насос и тп, то есть разных загрузок можно». Движение выбирается по тому,
    /// как работает сам объект: напорная станция гонит воду ровно, канализационная — толчками, как
    /// ручным насосом, тепловой пункт не гонит ничего, а греет, у задвижки крутится вентиль, а в
    /// пожарном шкафу вода тушит огонь.
    ///
    /// Строка, а не перечисление: на той стороне это Tag полосы, который разбирают триггеры XAML.</summary>
    public static string BarTag(EquipmentMotif motif) => motif switch
    {
        EquipmentMotif.Sewage => "hand",
        EquipmentMotif.HeatPoint => "heat",
        EquipmentMotif.Valve => "valve",
        EquipmentMotif.Fire => "fire",
        _ => "pump",
    };

    /// <summary>СХЕМА ОБЪЕКТА — то, ради чего стилизация и затевалась.
    ///
    /// Замечание Ильи: «стилизации мало, та что есть кривая». Значка в 24 пикселя действительно мало:
    /// он отвечает «что это», но не показывает, ЧТО СЕЙЧАС ПРОИСХОДИТ. Схема показывает: вода идёт
    /// из приёмника через насос в напорную линию, стоки — так же, но снизу вверх из колодца, тепло
    /// — по кругу через теплообменник.
    ///
    /// Рисуется линиями, а не картинкой: линии масштабируются без потери резкости на любом DPI (у
    /// этой машины 125 %), красятся кистью темы и не тянут за собой файлов ресурсов.
    ///
    /// Геометрия задана в системе координат 100×40 и растягивается по ширине окна.</summary>
    public static Geometry Scheme(EquipmentMotif motif) => Geometry.Parse(motif switch
    {
        // Приёмный резервуар → насос → напорная линия со стрелкой.
        EquipmentMotif.PumpStation =>
            "M4,28 L4,12 M4,28 L20,28 M20,28 L20,12 " +
            "M20,24 L34,24 " +
            "M42,24 m-8,0 a8,8 0 1,0 16,0 a8,8 0 1,0 -16,0 " +
            "M42,16 L42,10 L96,10 M90,6 L96,10 L90,14",
        // Колодец → насос над ним → выброс в напорную линию.
        EquipmentMotif.Sewage =>
            "M6,34 L6,16 M20,34 L20,16 M6,34 L20,34 " +
            "M13,30 L13,22 " +
            "M13,16 m-6,0 a6,6 0 1,0 12,0 a6,6 0 1,0 -12,0 " +
            "M19,12 L96,12 M90,8 L96,12 L90,16",
        // Контур отопления: подача, теплообменник, обратка.
        EquipmentMotif.HeatPoint =>
            "M4,12 L36,12 M4,28 L36,28 " +
            "M36,6 L56,6 L56,34 L36,34 Z " +
            "M56,12 L96,12 M56,28 L96,28 M90,8 L96,12 L90,16",
        // Пожарный шкаф: гидрант слева, дуга струи и очаг справа. Рисуется теми же тремя-четырьмя
        // линиями, что и остальные схемы: узнаваемость тут важнее подробностей.
        EquipmentMotif.Fire =>
            "M10,34 L10,12 M5,34 L15,34 M4,20 L16,20 M7,12 L13,12 M13,8 L13,12 " +
            "M16,16 C34,6 52,6 68,16 " +
            "M76,34 C70,28 77,23 77,16 C82,22 85,27 81,34 Z M88,34 C82,26 91,21 90,12 C97,20 98,28 93,34 Z",
        // Задвижка на линии.
        EquipmentMotif.Valve =>
            "M4,20 L36,20 M60,20 L96,20 " +
            "M36,10 L36,30 L48,20 Z M60,10 L60,30 L48,20 Z " +
            "M48,20 L48,6 M40,6 L56,6",
        _ => "",
    });
}
