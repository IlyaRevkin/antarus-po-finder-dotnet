using System.Windows.Media;
using AntarusPoFinder.Core.Domain;

namespace AntarusPoFinder.App;

/// <summary>КАК МОТИВ ОБОРУДОВАНИЯ ВЫГЛЯДИТ: значок, цвет и характер движения.
///
/// Вынесено из окна загрузки, когда мотив понадобился во втором месте — в карточке выдачи. Две
/// копии одних и тех же геометрий разъехались бы при первой же правке, и «насос в поиске» перестал
/// бы совпадать с «насосом при заливке»: человек читает их как один и тот же знак, и расхождение
/// он заметит раньше, чем мы.
///
/// Цвета — КЛЮЧАМИ кистей темы, а не числами: приложение живёт в четырёх темах, и захардкоженный
/// синий в «Стекле» выглядел бы заплаткой. Тему к тому же могут переключить прямо во время
/// заливки.</summary>
public static class EquipmentMotifArt
{
    /// <summary>Ключ кисти темы для этого мотива.</summary>
    public static string BrushKey(EquipmentMotif motif) => motif switch
    {
        // Стоки — не питьевая вода, и цвет у них свой: на экране это первое, что отличает КНС от
        // обычной насосной, ещё до того, как прочитана подпись.
        EquipmentMotif.Sewage => "SuccessBrush",
        EquipmentMotif.HeatPoint => "WarningBrush",
        EquipmentMotif.Valve => "CautionBrush",
        _ => "AccentBrush",
    };

    /// <summary>Значок мотива. Геометрии простые намеренно: это метка в 14–18 пикселей рядом с
    /// текстом, а не иллюстрация — в ней должно читаться одно: «это насос», «это тепло».</summary>
    public static Geometry Icon(EquipmentMotif motif) => Geometry.Parse(motif switch
    {
        // Насос: улитка корпуса и напорный патрубок вверх.
        EquipmentMotif.PumpStation => "M12,13 m-6,0 a6,6 0 1,0 12,0 a6,6 0 1,0 -12,0 M12,7 L12,3 L17,3 L17,5 L14,5 L14,7 Z",
        // Канализационная: та же улитка, но с подводящим лотком снизу — качает из приёмника.
        EquipmentMotif.Sewage => "M12,11 m-5,0 a5,5 0 1,0 10,0 a5,5 0 1,0 -10,0 M3,19 L21,19 L21,21 L3,21 Z M12,16 L12,19",
        // Тепловой пункт: две волны тепла.
        EquipmentMotif.HeatPoint => "M7,20 C7,16 11,15 11,11 C11,7 7,6 7,2 L9,2 C9,6 13,7 13,11 C13,15 9,16 9,20 Z M15,20 C15,16 19,15 19,11 C19,7 15,6 15,2 L17,2 C17,6 21,7 21,11 C21,15 17,16 17,20 Z",
        // Задвижка: корпус, шток и штурвал.
        _ => "M4,10 L20,10 L20,14 L4,14 Z M11,10 L11,5 L13,5 L13,10 Z M8,3 L16,3 L16,5 L8,5 Z",
    });

    /// <summary>Сколько секунд длится один пробег «потока» по полосе загрузки.
    ///
    /// Разная для разных мотивов не ради разнообразия: вода в напорной станции идёт быстро, стоки
    /// — медленно и тяжело, тепло не «бежит» вовсе, а пульсирует. Это и есть то, что отличает их
    /// боковым зрением, когда читать подпись некогда.</summary>
    public static double FlowSeconds(EquipmentMotif motif) => motif switch
    {
        EquipmentMotif.PumpStation => 1.6,
        EquipmentMotif.Sewage => 3.2,
        EquipmentMotif.HeatPoint => 2.4,
        _ => 2.0,
    };

    /// <summary>Пульсирует ли мотив вместо бегущего потока. У теплового пункта ничего не «течёт» по
    /// трубе на виду — греет, поэтому движение другое.</summary>
    public static bool Pulses(EquipmentMotif motif) => motif == EquipmentMotif.HeatPoint;

    /// <summary>СХЕМА ОБЪЕКТА — то, ради чего стилизация и затевалась.
    ///
    /// Замечание Ильи: «стилизации мало, та что есть кривая». Значка в 24 пикселя действительно мало:
    /// он отвечает «что это», но не показывает, ЧТО СЕЙЧАС ПРОИСХОДИТ. Схема показывает: вода идёт
    /// из приёмника через насос в напорную линию, стоки — так же, но снизу вверх из колодца, тепло
    /// — по кругу через теплообменник.
    ///
    /// Рисуется линиями, а не картинкой: линии масштабируются без потери резкости на любом DPI (у
    /// этой машины 125 %), красятся кистью темы и не тянут за собой файлов ресурсов.
    ///
    /// Геометрия задана в системе координат 100×40 и растягивается по ширине окна.</summary>
    public static Geometry Scheme(EquipmentMotif motif) => Geometry.Parse(motif switch
    {
        // Приёмный резервуар слева, насос в середине, напорная линия вправо и вверх.
        EquipmentMotif.PumpStation =>
            "M2,30 L2,12 M2,30 L22,30 M22,30 L22,20 " +            // резервуар
            "M22,25 L40,25 " +                                      // всас
            "M48,25 m-8,0 a8,8 0 1,0 16,0 a8,8 0 1,0 -16,0 " +      // насос
            "M48,17 L48,9 L62,9 " +                                 // напор вверх
            "M62,9 L98,9 M92,5 L98,9 L92,13",                       // линия и стрелка
        // Колодец (глубже и уже), насос, выброс наверх.
        EquipmentMotif.Sewage =>
            "M6,38 L6,14 M20,38 L20,14 M6,38 L20,38 " +             // колодец
            "M13,30 L13,22 " +                                      // всас снизу
            "M13,14 m-7,0 a7,7 0 1,0 14,0 a7,7 0 1,0 -14,0 " +      // насос над колодцем
            "M20,10 L60,10 M60,10 L60,30 L98,30 " +                 // напорная линия
            "M92,26 L98,30 L92,34",
        // Контур отопления: подача, теплообменник, обратка — кольцо.
        EquipmentMotif.HeatPoint =>
            "M4,10 L40,10 M4,30 L40,30 " +                          // подача и обратка
            "M44,4 L44,36 M60,4 L60,36 M44,4 L60,4 M44,36 L60,36 " +// теплообменник
            "M40,10 L44,10 M40,30 L44,30 " +
            "M60,10 L98,10 M60,30 L98,30 " +
            "M92,6 L98,10 L92,14",
        // Задвижка на линии: корпус со штоком и штурвалом.
        EquipmentMotif.Valve =>
            "M2,20 L38,20 M62,20 L98,20 " +
            "M38,10 L62,30 M38,30 L62,10 M38,10 L38,30 M62,10 L62,30 " +
            "M50,10 L50,2 M42,2 L58,2",
        _ => "",
    });
}
