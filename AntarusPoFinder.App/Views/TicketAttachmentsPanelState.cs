namespace AntarusPoFinder.App.Views;

/// <summary>Что показывать в разделе «Вложения» окна тикета.
///
/// Вынесено из разметки отдельным решением, потому что случая три, а не два, и путать их нельзя:
/// «вложений нет» и «мы не можем о них узнать» — разные вещи. Вложения лежат на сетевом диске
/// (TicketSyncService.AttachmentsDir); когда диск не подключён, честный ответ — «отсюда не видно»,
/// а не «нет».
///
/// Жалоба, с которой это заведено: «в тикетах зачем отображать „открыть папку вложений" или
/// „открыть вложение", если их нет». Незачем: кнопка, которая в ответ на нажатие может только
/// сообщить, что нажимать было не на что, — это не кнопка.</summary>
public readonly record struct TicketAttachmentsPanelState(bool ShowSection, bool ShowList, bool ShowButtons, string Note)
{
    public static TicketAttachmentsPanelState For(bool shareAvailable, int fileCount)
    {
        // Вложения есть — показываем всё: заголовок, список и обе кнопки.
        if (fileCount > 0) return new(true, true, true, "");

        // Диск на месте, вложений нет — раздела нет совсем. Ни заголовка, ни надписи «нет
        // вложений», ни кнопок: пустая строка о пустоте тоже занимает место и тоже требует
        // прочтения, а сказать ей нечего.
        if (shareAvailable) return new(false, false, false, "");

        // Диска нет — сказать об этом надо, иначе человек решит, что вложения потерялись. Кнопки
        // при этом всё равно убраны: открывать нечего, папки на этой машине не существует.
        return new(true, false, false,
            "Сетевой диск не подключён — если к тикету приложены файлы, отсюда их не видно.");
    }
}
